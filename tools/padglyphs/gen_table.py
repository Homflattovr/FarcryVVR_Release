"""tools\\padglyphs\\gen_table.py <game_textures dir> <out .h>: FarCry5PadGlyphTable.h, the game's button icons by the FNV-1a 64 of their BC3 data.

The textures are the game's own (ui\\common\\textures\\buttons\\crossplatform\\<set>\\tx_*.xbt, from patch.dat and worlds\\installpkg.dat, unpacked to
research\\2026-11-06_padglyphs\\game_textures as <set>_<name>.xbt). An .xbt is a 0x24-byte TBX header, a DDS header with a DX10 extension
(BC3_UNORM, one mip), then the data the game hands CreateTexture2D. Run with py -3 -I.
"""
import os, re, struct, sys

PAD = {'button1': 'A', 'button2': 'B', 'button3': 'X', 'button4': 'Y', 'shoulderleft1': 'LB', 'shoulderleft2': 'LT', 'shoulderright1': 'RB',
       'shoulderright2': 'RT', 'leftstick': 'LS', 'rightstick': 'RS', 'leftstickpress': 'LSPress', 'rightstickpress': 'RSPress',
       'leftstickpress_64x64': 'LSPress', 'rightstickpress_64x64': 'RSPress', 'pad': 'DPad', 'padup': 'DUp', 'paddown': 'DDown',
       'padleft': 'DLeft', 'padright': 'DRight', 'start': 'Start', 'select': 'Back', 'qte_ls': 'LS', 'qte_shoulderleft1_up': 'LB',
       'qte_shoulderleft2_up': 'LT', 'qte_shoulderright1_up': 'RB', 'qte_shoulderright2_up': 'RT'}
MOUSE = {'m_lb': 'Left', 'm_rb': 'Right', 'm_mb': 'Middle', 'm_wheel': 'Wheel', 'm_wheel_up': 'WheelUp', 'm_wheel_down': 'WheelDown'}


def fnv(b):
    h = 1469598103934665603
    for x in b:
        h = ((h ^ x) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h


def main(src, out):
    rows, seen = [], {}
    for f in sorted(os.listdir(src)):
        if not f.endswith('.xbt'):
            continue
        d = open(os.path.join(src, f), 'rb').read()
        o = d.find(b'DDS ')
        h, w = struct.unpack_from('<II', d, o + 12)
        fmt = struct.unpack_from('<I', d, o + 128)[0] if d[o + 84:o + 88] == b'DX10' else 0
        if fmt != 77:
            continue
        data = d[o + 128 + 20:]
        if len(data) != (w // 4) * (h // 4) * 16 and len(data) != ((w + 3) // 4) * ((h + 3) // 4) * 16:
            print('size?', f, len(data), w, h)
            continue
        m = re.match(r'(xboxone|xenon|ps4|third_party|kbm)_tx_(.*)\.xbt$', f)
        if not m:
            continue
        kset, name = m.group(1), m.group(2)
        if kset == 'kbm':
            k = re.match(r'key_(\d+)(_[a-z]+)?$', name)
            if k:
                entry = ('Key', int(k.group(1)))
            elif name in MOUSE:
                entry = ('Mouse', 'Mouse::' + MOUSE[name])
            else:
                continue
        else:
            if name not in PAD:
                continue
            entry = ('Pad', 'Pad::' + PAD[name])
        hh = fnv(data)
        if hh in seen and seen[hh] != entry:
            print('conflict', f, seen[hh], entry)
        seen[hh] = entry
        rows.append((hh, w, h, entry, '%s %s' % (kset, name)))
    with open(out, 'w', newline='\n') as o:
        o.write('#pragma once\n// Generated by tools\\padglyphs\\gen_table.py from the game\'s button icons (research\\2026-11-06_padglyphs\\game_textures):\n')
        o.write('// the FNV-1a 64 of each icon\'s BC3 data (as CreateTexture2D receives it), its size, and what it shows. Do not edit by hand.\n')
        o.write('#include <cstdint>\n\nnamespace fc5::padglyph\n{\n')
        o.write('    enum class Kind : uint8_t { Pad, Key, Mouse };\n')
        o.write('    // The pad buttons as the game names its icons (tx_shoulderleft1 is LB, tx_shoulderleft2 LT).\n')
        o.write('    enum class Pad : uint8_t { A, B, X, Y, LB, RB, LT, RT, LS, RS, LSPress, RSPress, DPad, DUp, DDown, DLeft, DRight, Start, Back, Count };\n')
        o.write('    enum class Mouse : uint8_t { Left, Right, Middle, Wheel, WheelUp, WheelDown, Count };\n')
        o.write('    struct Known\n    {\n        uint64_t    hash;\n        uint16_t    w, h;\n        Kind        kind;\n        uint8_t     code;   // Pad, Mouse, or the key\'s DirectInput scan code\n        const char* name;   // set and file\n    };\n')
        o.write('    inline constexpr Known kKnown[]{\n')
        for hh, w, h, (kind, code), nm in rows:
            c = code if isinstance(code, int) else 'uint8_t(%s)' % code
            o.write('        { 0x%016xull, %d, %d, Kind::%s, %s, "%s" },\n' % (hh, w, h, kind, c, nm))
        o.write('    };\n}\n')
    print(len(rows), 'icons')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
